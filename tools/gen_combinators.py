#!/usr/bin/env python3
"""Writes skivine/combinators.vi from tools/birds.py.

Each bird of arity n becomes n enum variants, one per number of arguments held
(0 to n - 1); `apply` adds an argument or, on the last one, builds the rule's
right-hand side out of further calls to `apply`."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from birds import BIRDS, FORMALS, parse_rule

from gen_combinators_excluded import EXCLUDED

BIRDS = tuple(b for b in BIRDS if b[0] not in EXCLUDED)

IDENT = {name: ident for name, ident, _, _, _ in BIRDS}


def uses(tree, v):
    return tree == v if isinstance(tree, str) else uses(tree[0], v) or uses(tree[1], v)


def body(tree, last):
    if isinstance(tree, str):
        if tree in IDENT and tree not in FORMALS:
            return f"Term::{IDENT[tree]}_0()"
        return "x" if tree == last else tree
    return f"apply({body(tree[0], last)}, {body(tree[1], last)})"


def variant(ident, k, args):
    return f"Term::{ident}_{k}({', '.join(args)})"


out = ['''
/// Combinator birds on interaction nets. Generated by tools/gen_combinators.py
/// from tools/birds.py; do not edit by hand.
///
/// A `Term` is a value: a bird that still lacks arguments. The variant
/// `X_k` is the bird `X` holding `k` arguments. Application is the function
/// `apply`; a term with a redex is never built, only evaluated.

pub enum Term {''']
for name, ident, bird, arity, rule in BIRDS:
    out.append(f"  // {name}: {bird}. {name} {' '.join(FORMALS[:arity])} -> {rule}")
    for k in range(arity):
        out.append(f"  {ident}_{k}({', '.join(['Term'] * k)}),")
out.append('''}

pub mod Term {
  // Fork and Drop are written out: deriving them for this many variants
  // exceeds the compiler's search limit (Vine cf0c325).

  /// Copies one variant and forks what it holds.
  pub impl : Fork[Term] {
    fn fork(&self: &Term) -> Term {
      match &self {''')
for name, ident, _, arity, _ in BIRDS:
    for k in range(arity):
        args = [f"x{i}" for i in range(k)]
        out.append(f"        &{variant(ident, k, args)} {{ {variant(ident, k, [a + '.fork()' for a in args])} }}")
out.append('''      }
    }
  }

  pub impl : Drop[Term] {
    fn drop(self: Term) {
      match self {''')
for name, ident, _, arity, _ in BIRDS:
    for k in range(1, arity):
        args = [f"x{i}" for i in range(k)]
        out.append(f"        {variant(ident, k, args)} {{ {' '.join(a + '.drop();' for a in args)} }}")
out.append('''        _ {}
      }
    }
  }

  /// `f x`. Matches on the function only, so `x` is passed on unevaluated.
  pub fn apply(f: Term, x: Term) -> Term {
    match f {''')
for name, ident, bird, arity, rule in BIRDS:
    tree = parse_rule(rule)
    formals = list(FORMALS[:arity])
    for k in range(arity - 1):
        held = formals[:k]
        out.append(f"      {variant(ident, k, held)} {{ {variant(ident, k + 1, held + ['x'])} }}")
    held = [v if uses(tree, v) else "_" for v in formals[:-1]]
    out.append(f"      {variant(ident, arity - 1, held)} {{ {body(tree, formals[-1])} }}")
out.append('''    }
  }

  /// Evaluates a term in prefix form. A backtick applies the next two terms;
  /// a bird is written by its name, and a space ends a name. So
  /// `` ``S K K `` is `S K K`. An unknown name, or the end of the input,
  /// reads as `I`.
  pub fn eval(src: String) -> Term {
    let chars = src as List[Char];
    eval_from(&chars)
  }

  fn eval_from(&chars: &List[Char]) -> Term {
    let name = [];
    while chars.pop_front() is Option::Some(c) {
      if c == '`' {
        let f = eval_from(&chars);
        let x = eval_from(&chars);
        return apply(f, x);
      }
      if c == ' ' {
        if name.len() != 0 {
          break;
        }
      } else {
        name.push_back(c);
      }
    }
    bird(name as String)
  }

  /// The bird with the given name, or `I`.
  pub fn bird(name: String) -> Term {
    when {''')
for name, ident, _, _, _ in BIRDS:
    out.append(f'      name == "{name}" {{ Term::{ident}_0() }}')
out.append('''      _ { Term::I_0() }
    }
  }

  /// The term in prefix form.
  pub fn .prefix(self: Term) -> String {
    let out = [];
    self.write(&out);
    out as String
  }

  fn .write(self: Term, &out: &List[Char]) {
    if out.len() != 0 {
      out.push_back(' ');
    }
    match self {''')
for name, ident, _, arity, _ in BIRDS:
    for k in range(arity):
        args = [f"x{i}" for i in range(k)]
        text = "`" * k + name
        lines = [f'        out ++= "{text}" as List[Char];'] + [f"        {a}.write(&out);" for a in args]
        out.append(f"      {variant(ident, k, args)} {{\n" + "\n".join(lines) + "\n      }")
out.append('''    }
  }

  /// The number of birds in the term.
  pub fn .size(self: Term) -> N32 {
    match self {''')
for name, ident, _, arity, _ in BIRDS:
    for k in range(1, arity):
        args = [f"x{i}" for i in range(k)]
        out.append(f"      {variant(ident, k, args)} {{ 1 + {' + '.join(a + '.size()' for a in args)} }}")
out.append('''      _ { 1 }
    }
  }
}
''')
path = os.path.join(os.path.dirname(HERE), "skivine", "combinators.vi")
open(path, "w").write("\n".join(out))
print(f"wrote {path}: {len(BIRDS)} birds, {sum(b[3] for b in BIRDS)} variants; left out: {sorted(EXCLUDED)}")
